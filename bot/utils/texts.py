def format_date(value: datetime) -> str:
    return value.strftime("%d.%m.%Y")


def profile_text(
    *, telegram_id: int, registered_at: datetime, notifications_enabled: bool, actions_count: int,
    builds_count: int = 0,
) -> str:
    notify = "включены" if notifications_enabled else "выключены"
    return (
        "👤 <b>Профиль</b>\n\n"
        f"🆔 Telegram ID: <code>{telegram_id}</code>\n"
        f"📅 Дата регистрации: {format_date(registered_at)}\n"
        f"📦 Сохранённых сборок: {builds_count}\n"
        f"📊 Действий в боте: {actions_count}\n\n"
        "⚙️ <b>Настройки</b>\n"
        f"🔔 Уведомления: {notify}"
    )


